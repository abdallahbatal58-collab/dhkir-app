const QURAN_API_BASE = "https://api.alquran.cloud/v1";

async function loadQuranSurahs() {
    const container = document.getElementById('list-quran');
    if (!container) return;

    try {
        const response = await fetch(`${QURAN_API_BASE}/surah`);
        const data = await response.json();
        
        if (data.code === 200) {
            const surahs = data.data;
            container.innerHTML = surahs.map(surah => `
                <div class="adhkar-card" style="cursor: pointer;" onclick="openSurah(${surah.number})">
                    <div style="display: flex; justify-content: space-between; align-items: center;">
                        <div>
                            <h3 style="color: var(--gold); font-family: 'Amiri'; font-size: 1.5rem;">${surah.name}</h3>
                            <p style="color: var(--text-muted); font-size: 0.9rem;">${surah.englishName} - ${surah.numberOfAyahs} آية</p>
                        </div>
                        <div style="background: var(--primary); color: var(--gold); width: 40px; height: 40px; display: flex; justify-content: center; align-items: center; border-radius: 50%; font-weight: bold; border: 1px solid var(--gold);">
                            ${surah.number}
                        </div>
                    </div>
                </div>
            `).join('');
        }
    } catch (error) {
        container.innerHTML = `<p style="text-align:center; color: red;">حدث خطأ أثناء تحميل القرآن. تأكد من اتصالك بالإنترنت.</p>`;
    }
}

// دالة فتح السورة (سيتم تطويرها لاحقاً لعرض الآيات)
function openSurah(surahNumber) {
    alert(`سيتم عرض السورة رقم ${surahNumber} قريباً بعد ربط نظام الآيات.`);
}

// تشغيل تحميل السور عند فتح الصفحة
document.addEventListener('DOMContentLoaded', () => {
    // ننتظر قليلاً حتى يتم تهيئة الصفحة
    setTimeout(loadQuranSurahs, 2000);
});